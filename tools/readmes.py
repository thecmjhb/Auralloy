#!/usr/bin/env python3
"""Generates README.md, README.bn.md and docs/i18n/README.<lang>.md from docs/i18n/locales/<lang>.json
and the benchmark numbers in benchmarks/results/summary.json.      python tools/readmes.py"""
import json, os, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOC = os.path.join(ROOT, "docs", "i18n", "locales")
VERSION = "0.0.1"
DOI = "10.5281/zenodo.24391795"
DOI_URL = "https://doi.org/" + DOI

ORDER = ["en", "bn", "zh-CN", "hi", "es", "ar", "fr", "pt", "id", "ur", "ru", "ko", "ja", "de", "tr", "it", "fa", "vi", "ta", "te"]

def load(code):
    with open(os.path.join(LOC, code + ".json"), encoding="utf-8") as f:
        return json.load(f)

def bench_numbers():
    p = os.path.join(ROOT, "benchmarks", "results", "summary.json")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)

def pct(x): return f"{x * 100:.1f} %"

def lang_path(code, from_root):
    """relative link to a language README"""
    if code == "en":
        return "README.md" if from_root else "../../README.md"
    if code == "bn":
        return "README.bn.md" if from_root else "../../README.bn.md"
    return f"docs/i18n/README.{code}.md" if from_root else f"README.{code}.md"

def chips(from_root, locs):
    pre = "" if from_root else "../../"
    items = []
    for code in ORDER:
        name = locs[code]["name"]
        w = 64 if len(name) >= 9 else 58
        items.append(f'<a href="{lang_path(code, from_root)}" title="{html.escape(name)}"><img src="{pre}assets/languages/{code}.svg" width="{w}" height="28" alt="{html.escape(name)}"></a>')
    return '<p align="center" dir="ltr">' + "".join(items[:10]) + "<br>" + "".join(items[10:]) + "</p>"

def render(code, locs, bench, from_root):
    L = locs[code]
    pre = "" if from_root else "../../"
    d = L["dir"]
    esc = html.escape
    out = []
    out.append(f"<!-- Generated by tools/readmes.py; edit docs/i18n/locales/{code}.json. -->")
    out.append('<div align="center">')
    out.append(f'  <img src="{pre}assets/banner.svg" alt="Auralloy" width="100%">')
    out.append(f"  <h3>{esc(L['tagline'])}</h3>")
    out.append(f"  <p>{esc(L['subtitle'])}</p>")
    out.append("  <p>")
    out.append(f'    <a href="https://github.com/thecmjhb/Auralloy/releases"><img src="https://img.shields.io/badge/Release-v{VERSION}-5cf2d6?style=flat-square" alt="Release v{VERSION}"></a>')
    out.append('    <img src="https://img.shields.io/badge/Platform-Windows_x64-9b8cff?style=flat-square" alt="Windows x64">')
    out.append('    <img src="https://img.shields.io/badge/C%2B%2B-17-ff6fb5?style=flat-square" alt="C++17">')
    out.append('    <img src="https://img.shields.io/badge/License-AGPL--3.0-22c55e?style=flat-square" alt="AGPL-3.0">')
    out.append('    <img src="https://img.shields.io/badge/Documentation-20_languages-ffc857?style=flat-square" alt="20 languages">')
    out.append(f'    <a href="{DOI_URL}"><img src="https://zenodo.org/badge/DOI/{DOI}.svg" alt="DOI {DOI}"></a>')
    out.append("  </p>")
    nav = [("demo", L["h_demo"]), ("what", L["h_what"]), ("start", L["h_start"]), ("rules", L["h_rules"]), ("bench", L["h_bench"]), ("paper", L["h_paper"])]
    out.append("  <p>" + " · ".join(f'<a href="#{a}">{esc(t)}</a>' for a, t in nav) + "</p>")
    out.append("</div>\n\n---\n")
    out.append(chips(from_root, locs) + "\n")

    wrap_open = f'<div dir="{d}">\n' if d == "rtl" else ""
    wrap_close = "</div>\n" if d == "rtl" else ""
    out.append(wrap_open)

    out.append(f'<a id="demo"></a>\n\n## 🎬 {L["h_demo"]}\n')
    out.append(f'<p align="center"><img src="{pre}assets/auralloy-demo.gif" alt="Auralloy demo" width="100%"></p>\n')
    out.append(f'<p align="center"><sub>{esc(L["demo_caption"])}</sub></p>\n')

    out.append(f'<a id="what"></a>\n\n## ✨ {L["h_what"]}\n')
    out.append("| | |\n|---|---|")
    icons = ["🎛️", "🔎", "🎚️", "🌧️", "💎", "🧪"]
    for i in range(6):
        out.append(f"| {icons[i]} **{L['f_t'][i]}** | {L['f_d'][i]} |")
    out.append("")

    out.append(f'## 🧭 {L["h_how"]}\n')
    out.append(f'<p align="center"><img src="{pre}assets/pipeline.svg" alt="pipeline" width="100%"></p>\n')
    for i, s in enumerate(L["how"], 1):
        out.append(f"{i}. {s}")
    out.append("")

    out.append(f'<a id="start"></a>\n\n## 🚀 {L["h_start"]}\n')
    for i, s in enumerate(L["start"], 1):
        out.append(f"{i}. {s}")
    out.append("")
    if code == "en":
        out.append("<details>\n<summary><b>Build from source (Windows)</b></summary>\n")
        out.append("Requirements: Visual Studio 2022 (C++ workload) or Build Tools, CMake 3.22+, git.\n")
        out.append("```bash\ncmake -B build -G \"Visual Studio 17 2022\" -A x64          # fetches JUCE at a pinned commit\ncmake --build build --config Release --target Auralloy\n# -> build/Auralloy_artefacts/Release/Auralloy.exe\n```\n")
        out.append("Use an existing JUCE checkout with `-DAURALLOY_JUCE_DIR=path/to/JUCE`. Run the tests with `-DAURALLOY_TESTS=ON`; regenerate the brand assets and the demo with `-DAURALLOY_TOOLS=ON`.\n")
        out.append("</details>\n")
        out.append("<details>\n<summary><b>Keyboard shortcuts</b></summary>\n")
        out.append("`Space` play · `S` split · `Del` delete · `Ctrl+D` duplicate · `Ctrl+Z / Ctrl+Y` undo / redo · `Alt+Z` undo a sound change · `L` loop · `B` FX bypass · `F` fit · `+ / -` zoom · `1 / 2` Studio / Forge · `Ctrl+O` add songs · `Ctrl+E` export · `Ctrl+S` save.\n")
        out.append("Timeline: wheel = zoom, `Ctrl`+wheel = pan, `Shift`+drag = loop region, double-click a clip = loop it. Knobs: hover + mouse wheel (`Shift` = fine), double-click = reset.\n")
        out.append("</details>\n")
    else:
        out.append(f"> {L['more']}\n")

    out.append(f'<a id="rules"></a>\n\n## 📐 {L["h_rules"]}\n')
    out.append(L["rules_intro"] + "\n")
    for s in L["rules"]:
        out.append(f"- {s}")
    out.append("\n" + ("Details: [docs/RULES.md](docs/RULES.md)\n" if from_root and code == "en" else ""))

    out.append(f'## 🖥️ {L["h_tour"]}\n')
    shots = [("screenshot-studio.png", L["tour"][0]), ("screenshot-forge.png", L["tour"][1]), ("screenshot-export.png", L["tour"][2])]
    for f, cap in shots:
        out.append(f'<p align="center"><img src="{pre}assets/{f}" alt="{esc(cap)}" width="100%"><br><sub>{esc(cap)}</sub></p>\n')

    out.append(f'<a id="bench"></a>\n\n## 📊 {L["h_bench"]}\n')
    out.append(L["bench_intro"] + "\n")
    if bench:
        a, m, s = bench["analysis"], bench["mashups"], bench["stems"]
        rows = [pct(a["tempo_within_0.5pct"]), pct(a["key_exact_or_relative"]), pct(a["downbeat_within_50ms"]), f'{a["boundary_f1"]:.2f}', pct(m["rule_compliance"]),
                f'{m["rendered_tempo_err_bpm_mean"]:.3f} BPM', f'{m["tempo_sd_across_windows_auralloy"]:.2f} vs {m["tempo_sd_across_windows_baseline"]:.2f} BPM']
        out.append("| | |\n|---|---:|")
        for lab, val in zip(L["bench_labels"], rows):
            out.append(f"| {lab} | **{val}** |")
        out.append("")
        out.append(f'<sub>{a["analysed"]} songs · {m["planned"]} planned mashups · stems SI-SDR vocals {s["si_sdr_vocals_db_mean"]:.1f} dB, drums {s["si_sdr_drums_db_mean"]:.1f} dB, bass {s["si_sdr_bass_db_mean"]:.1f} dB · seed {bench["seed"]}</sub>\n')

    out.append(f'## ⚠️ {L["h_limits"]}\n')
    for s in L["limits"]:
        out.append(f"- {s}")
    out.append("")

    out.append(f'<a id="paper"></a>\n\n## 📄 {L["h_paper"]}\n')
    out.append(f'<p align="center"><a href="{DOI_URL}"><img src="https://img.shields.io/badge/Zenodo-10.5281%2Fzenodo.24391795-2563eb?style=for-the-badge" alt="Zenodo DOI"></a> <a href="{pre}paper/Auralloy-preprint.pdf"><img src="https://img.shields.io/badge/Read_the_preprint-PDF-2563eb?style=for-the-badge" alt="Preprint PDF"></a></p>\n')
    out.append(f"**Auralloy: Rule-Grounded, Explainable Multi-Song Mashup Generation with an Editable Stem Timeline**  \nC. M. Jubayer Hossain Bappy · 2026 · [{DOI}]({DOI_URL})\n")
    out.append(L["paper"] + "\n")
    out.append("<details>\n<summary><b>BibTeX</b></summary>\n")
    out.append("```bibtex\n@misc{bappy2026auralloy,\n  author    = {Hossain Bappy, C. M. Jubayer},\n  title     = {Auralloy: Rule-Grounded, Explainable Multi-Song Mashup Generation with an Editable Stem Timeline},\n  year      = {2026},\n  publisher = {Zenodo},\n  doi       = {" + DOI + "},\n  url       = {" + DOI_URL + "}\n}\n```\n")
    out.append("GitHub also shows a *Cite this repository* button (from `CITATION.cff`).\n")
    out.append("</details>\n")
    if code == "en":
        out.append('<a id="faq"></a>\n\n## ❓ FAQ\n')
        faq = [
            ("How many songs do I need?", "At least two, and there is no upper limit. Songs whose tempo is more than 15 % away from the shared target, or whose key needs more than 3 semitones of shift, are left out, and the log tells you which and why."),
            ("Is there AI or a cloud service involved?", "No. Auralloy is classic signal processing plus written rules. It runs locally, needs no GPU and makes no network connections."),
            ("How good is the stem separation?", "Quick Stems is a lightweight DSP separator: decent for a centred lead vocal and bass, weak for drums. A neural separator can replace it behind one function. See the benchmark numbers above."),
            ("Will it work on my real music?", "It was validated on synthetic songs only; real recordings are harder (see *Honest limitations*). Please report what goes wrong with an issue."),
            ("Which platforms are supported?", "The release is Windows x64. The code is portable C++17 on JUCE, but macOS and Linux builds are untested."),
            ("Can I mash up copyrighted songs?", "Auralloy is a tool. You are responsible for the rights to the audio you import and for what you publish."),
        ]
        for q, ans in faq:
            out.append(f"<details>\n<summary><b>{q}</b></summary>\n\n{ans}\n\n</details>\n")
        out.append("## 🗺️ Roadmap\n")
        for r in ["A listening study on real music (with permission)", "Pluggable neural stem separator behind `separateStems()`", "Tempo-varying beat tracking and a downbeat model that is robust at fast tempos", "macOS and Linux builds, signed Windows installer", "More one-click looks and a batch mode"]:
            out.append(f"- [ ] {r}")
        out.append("\nIdeas and bug reports are welcome: see [CONTRIBUTING.md](CONTRIBUTING.md).\n")
    else:
        out.append(f"[CONTRIBUTING]({pre}CONTRIBUTING.md) · [CHANGELOG]({pre}CHANGELOG.md) · [SECURITY]({pre}SECURITY.md)\n")
    out.append(f'## ⚖️ {L["h_license"]}\n')
    out.append(f"{L['license']} {L['rights']}\n")
    out.append(wrap_close)
    out.append('<p align="center"><sub>© C. M. Jubayer Hossain Bappy · <a href="LICENSE">AGPL-3.0</a></sub></p>\n'.replace('href="LICENSE"', f'href="{pre}LICENSE"'))
    return "\n".join(out)

def main():
    locs = {c: load(c) for c in ORDER}
    bench = bench_numbers()
    os.makedirs(os.path.join(ROOT, "docs", "i18n"), exist_ok=True)
    for code in ORDER:
        if code == "en":
            path = os.path.join(ROOT, "README.md"); from_root = True
        elif code == "bn":
            path = os.path.join(ROOT, "README.bn.md"); from_root = True
        else:
            path = os.path.join(ROOT, "docs", "i18n", f"README.{code}.md"); from_root = False
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(code, locs, bench, from_root))
    print("generated", len(ORDER), "READMEs")

if __name__ == "__main__":
    main()
